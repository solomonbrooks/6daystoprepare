"""Builds Wren: an original Mii-style doll for the sixth night.

Writes wren.obj, wren.mtl and wren-face.png next to this file.
Units are blocks; she stands about 1.45 blocks tall, facing +Z.
Run: python3 build.py   (needs numpy and Pillow)
"""
import math
import os

import numpy as np
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))

SKIN = (0.78, 0.80, 0.83)
HAIR = (0.08, 0.07, 0.09)
DRESS = (0.19, 0.11, 0.21)
COLLAR = (0.90, 0.88, 0.84)
STOCKING = (0.15, 0.15, 0.17)
SHOE = (0.05, 0.05, 0.06)

HEAD_C = np.array([0.0, 1.12, 0.0])
HEAD_R = np.array([0.24, 0.27, 0.23])


class Mesh:
    def __init__(self):
        self.v, self.vt, self.vn = [], [], []
        self.parts = []  # (name, material, faces)

    def part(self, name, mtl, verts, uvs, normals, tris):
        base_v, base_t = len(self.v), len(self.vt)
        self.v += [tuple(p) for p in verts]
        self.vn += [tuple(n / (np.linalg.norm(n) or 1)) for n in normals]
        self.vt += [tuple(t) for t in uvs]
        faces = [tuple(base_v + i for i in tri) for tri in tris]
        self.parts.append((name, mtl, faces, base_t))

    def write(self, path, mtllib):
        with open(path, "w") as f:
            f.write("# Wren, generated by build.py\n")
            f.write(f"mtllib {mtllib}\n")
            for p in self.v:
                f.write("v %.4f %.4f %.4f\n" % p)
            for t in self.vt:
                f.write("vt %.4f %.4f\n" % t)
            for n in self.vn:
                f.write("vn %.4f %.4f %.4f\n" % n)
            for name, mtl, faces, _ in self.parts:
                f.write(f"o {name}\nusemtl {mtl}\ns 1\n")
                for a, b, c in faces:
                    # vertex, uv and normal arrays share indices
                    f.write(f"f {a+1}/{a+1}/{a+1} {b+1}/{b+1}/{b+1} {c+1}/{c+1}/{c+1}\n")


def ellipsoid(mesh, name, mtl, center, radii, nu=48, nv=32):
    """UV sphere scaled to radii."""
    verts, uvs, norms, index = [], [], [], {}
    for j in range(nv + 1):
        phi = math.pi * j / nv
        for i in range(nu + 1):
            theta = 2 * math.pi * i / nu - math.pi
            d = np.array([math.sin(phi) * math.sin(theta), math.cos(phi), math.sin(phi) * math.cos(theta)])
            p = center + d * radii
            index[(i, j)] = len(verts)
            verts.append(p)
            norms.append(d / radii ** 2)
            uvs.append((i / nu, 1 - j / nv))
    tris = []
    for j in range(nv):
        for i in range(nu):
            a, b = index[(i, j)], index[(i + 1, j)]
            c, e = index[(i + 1, j + 1)], index[(i, j + 1)]
            tris += [(a, e, c), (a, c, b)]
    mesh.part(name, mtl, verts, uvs, norms, tris)


def tube(mesh, name, mtl, p0, p1, r0, r1, n=24, caps=True):
    p0, p1 = np.asarray(p0, float), np.asarray(p1, float)
    axis = p1 - p0
    length = np.linalg.norm(axis)
    w = axis / length
    u = np.cross(w, [0, 0, 1] if abs(w[2]) < 0.9 else [1, 0, 0])
    u /= np.linalg.norm(u)
    v = np.cross(w, u)
    slope = (r0 - r1) / length
    verts, uvs, norms, tris = [], [], [], []
    for k in range(n + 1):
        a = 2 * math.pi * k / n
        radial = u * math.cos(a) + v * math.sin(a)
        for p, r in ((p0, r0), (p1, r1)):
            verts.append(p + radial * r)
            norms.append(radial + w * slope)
            uvs.append((k / n, 0.0 if p is p0 else 1.0))
    for k in range(n):
        a, b, c, d = 2 * k, 2 * k + 1, 2 * k + 3, 2 * k + 2
        tris += [(a, d, c), (a, c, b)]
    if caps:
        for p, r, sign in ((p0, r0, -1), (p1, r1, 1)):
            centre = len(verts)
            verts.append(p)
            norms.append(w * sign)
            uvs.append((0.5, 0.5))
            ring = []
            for k in range(n):
                a = 2 * math.pi * k / n
                ring.append(len(verts))
                verts.append(p + (u * math.cos(a) + v * math.sin(a)) * r)
                norms.append(w * sign)
                uvs.append((0.5, 0.5))
            for k in range(n):
                x, y = ring[k], ring[(k + 1) % n]
                tris.append((centre, x, y) if sign > 0 else (centre, y, x))
    mesh.part(name, mtl, verts, uvs, norms, tris)


FACE_HALF_WIDTH = 0.95  # radians either side of her nose left open by the hair
BOB_END = math.acos(-0.62)  # the hair stops at the jaw


def fringe(theta):
    # the fringe sweeps down towards her left
    return math.acos(0.42 - 0.17 * math.sin(theta))


def hair(mesh, center, radii, nu=96, nv=40):
    """A blunt bob: a cap down to the fringe all the way round, then a
    curtain down to the jaw everywhere except the face. Built as two
    grids whose edges follow the cut, so the outline stays smooth."""
    verts, uvs, norms, tris = [], [], [], []

    def grid(thetas, phi_top, phi_bottom):
        base = len(verts)
        for i, theta in enumerate(thetas):
            top, bottom = phi_top(theta), phi_bottom(theta)
            for j in range(nv + 1):
                phi = top + (bottom - top) * j / nv
                d = np.array([math.sin(phi) * math.sin(theta), math.cos(phi), math.sin(phi) * math.cos(theta)])
                verts.append(center + d * radii * (1.07 + 0.10 * max(0.0, -d[1]) ** 2))
                norms.append(d / radii ** 2)
                uvs.append((i / (len(thetas) - 1), 1 - phi / math.pi))
        for i in range(len(thetas) - 1):
            for j in range(nv):
                a = base + i * (nv + 1) + j
                b, c, e = a + nv + 1, a + nv + 2, a + 1
                tris.extend([(a, e, c), (a, c, b)])

    around = [2 * math.pi * i / nu - math.pi for i in range(nu + 1)]
    grid(around, lambda t: 0.0, fringe)
    back = [FACE_HALF_WIDTH + (2 * math.pi - 2 * FACE_HALF_WIDTH) * i / nu for i in range(nu + 1)]
    grid(back, fringe, lambda t: BOB_END)
    mesh.part("hair", "hair", verts, uvs, norms, tris)


def face_texture(path, size=2048):
    w, h = size, size // 2
    img = Image.new("RGB", (w, h), tuple(int(c * 255) for c in SKIN))
    g = ImageDraw.Draw(img)
    ink = (22, 20, 26)
    cx, s = w // 2, w / 2048  # s keeps the drawing resolution-independent

    def P(x, y):
        return (cx + x * s, y * s)

    def box(x0, y0, x1, y1):
        return [P(x0, y0), P(x1, y1)]

    for side in (-1, 1):
        ex = side * 140
        # sleepless rings under the eyes
        g.arc(box(ex - 62, 440, ex + 62, 560), 20, 160, fill=(150, 140, 165), width=int(10 * s))
        # wide, pale eyes with pinprick pupils that look slightly off to one side
        g.ellipse(box(ex - 52, 432, ex + 52, 520), fill=(240, 240, 236), outline=ink, width=int(7 * s))
        g.ellipse(box(ex + 8 - 9, 466, ex + 8 + 9, 484), fill=ink)
        # flat, heavy brows, tipped up at the inner end
        inner, outer = ex - side * 50, ex + side * 50
        g.line([P(inner, 388), P(outer, 410)], fill=ink, width=int(12 * s))

    # a small hooked nose
    g.arc(box(-22, 540, 14, 590), 300, 120, fill=ink, width=int(7 * s))

    # a long stitched-shut smile
    pts = [P(x, 652 - 22 * math.cos(x / 95 * math.pi / 2)) for x in range(-95, 96, 5)]
    g.line(pts, fill=ink, width=int(7 * s))
    for x in range(-80, 81, 26):
        y = 652 - 22 * math.cos(x / 95 * math.pi / 2)
        g.line([P(x - 9, y - 13), P(x + 9, y + 13)], fill=ink, width=int(6 * s))
        g.line([P(x + 9, y - 13), P(x - 9, y + 13)], fill=ink, width=int(6 * s))

    # a plaster on her left cheek
    patch = Image.new("RGBA", (int(96 * s), int(40 * s)), (0, 0, 0, 0))
    pg = ImageDraw.Draw(patch)
    pg.rounded_rectangle([0, 0, patch.width - 1, patch.height - 1], radius=int(12 * s), fill=(226, 205, 176, 255), outline=(150, 128, 104, 255), width=int(3 * s))
    pg.rectangle([patch.width * 0.33, 4 * s, patch.width * 0.67, patch.height - 4 * s], fill=(240, 226, 204, 255))
    for k in range(3):
        for m in range(2):
            x = patch.width * (0.40 + 0.10 * k)
            y = patch.height * (0.35 + 0.30 * m)
            pg.ellipse([x - 2 * s, y - 2 * s, x + 2 * s, y + 2 * s], fill=(170, 148, 120, 255))
    patch = patch.rotate(24, expand=True, resample=Image.BICUBIC)
    img.paste(patch, (int(cx + 205 * s - patch.width / 2), int(590 * s - patch.height / 2)), patch)
    img.save(path)


def build():
    m = Mesh()
    # head and hair
    ellipsoid(m, "head", "face", HEAD_C, HEAD_R, nu=48, nv=32)
    hair(m, HEAD_C + [0, 0.01, -0.005], HEAD_R)
    # neck, collar, dress
    tube(m, "neck", "skin", [0, 0.80, 0], [0, 0.90, 0], 0.045, 0.045)
    tube(m, "dress", "dress", [0, 0.40, 0], [0, 0.84, 0], 0.21, 0.10, n=32)
    ellipsoid(m, "collar", "collar", np.array([0, 0.835, 0.005]), np.array([0.13, 0.03, 0.115]), nu=32, nv=12)
    ellipsoid(m, "button", "shoe", np.array([0, 0.74, 0.122]), np.array([0.014, 0.014, 0.008]), nu=12, nv=8)
    # arms hang stiffly at her sides
    for side, label in ((-1, "r"), (1, "l")):
        shoulder = [side * 0.085, 0.80, 0]
        wrist = [side * 0.215, 0.52, 0.02]
        tube(m, f"arm_{label}", "dress", shoulder, wrist, 0.036, 0.030)
        ellipsoid(m, f"hand_{label}", "skin", np.array([side * 0.225, 0.49, 0.022]), np.array([0.042, 0.048, 0.042]), nu=20, nv=14)
        tube(m, f"leg_{label}", "stocking", [side * 0.07, 0.42, 0], [side * 0.07, 0.04, 0], 0.034, 0.030)
        ellipsoid(m, f"shoe_{label}", "shoe", np.array([side * 0.07, 0.035, 0.022]), np.array([0.048, 0.035, 0.075]), nu=20, nv=12)
    m.write(os.path.join(HERE, "wren.obj"), "wren.mtl")

    def mat(name, rgb, tex=None):
        line = f"newmtl {name}\nKa 0 0 0\nKd {rgb[0]:.3f} {rgb[1]:.3f} {rgb[2]:.3f}\nKs 0 0 0\nd 1\nillum 1\n"
        return line + (f"map_Kd {tex}\n" if tex else "") + "\n"

    with open(os.path.join(HERE, "wren.mtl"), "w") as f:
        f.write(mat("face", (1, 1, 1), "wren-face.png"))
        f.write(mat("skin", SKIN) + mat("hair", HAIR) + mat("dress", DRESS))
        f.write(mat("collar", COLLAR) + mat("stocking", STOCKING) + mat("shoe", SHOE))
    face_texture(os.path.join(HERE, "wren-face.png"))


if __name__ == "__main__":
    build()
